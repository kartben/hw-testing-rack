#!/usr/bin/env python3
"""hw-testing-rack build driver.

    python tools/build.py config      # regenerate mechanical/generated/*.scad
    python tools/build.py stl         # render every printable part to STL (OpenSCAD)
    python tools/build.py web         # STL/GLB models + site/assets/rack.json for the 3D viewer
    python tools/build.py all

OpenSCAD is used from PATH if present, otherwise through the
`openscad/openscad` Docker image.  Run with any Python ≥3.10 that has
`pyyaml`, `numpy` and `trimesh` (see tools/requirements.txt).
"""

from __future__ import annotations

import argparse
import concurrent.futures as cf
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import plate_layout  # noqa: E402
import rackcfg  # noqa: E402

REPO = rackcfg.REPO
MECH = REPO / "mechanical"
GEN = MECH / "generated"
BUILD = MECH / "build"
SITE_ASSETS = REPO / "site" / "assets"


# ------------------------------------------------------------------ config

def board_record(bid: str, b: dict, o: dict) -> list:
    """A BOARD_DB row: the board turned as `o` (rackcfg.orient_board) says."""
    return [
        bid, b.get("short", b["name"]), [round(o["w"], 3), round(o["l"], 3)], b.get("hole_d", 3.2),
        [[round(x, 3), round(y, 3)] for x, y in o["holes"]], round(o["usb_x"], 3),
        b.get("usb", {}).get("type", "usb-c"), b.get("standoff", 6), bool(b.get("fence", False)),
        b.get("height", 10), b.get("color", "#1b5e20"), bool(b.get("verified", False)), bool(o["usb_side"]),
    ]


def boards_scad(boards: dict, rack=None) -> str:
    rows = [rackcfg.scad_value(board_record(bid, b, rackcfg.orient_board(b))) for bid, b in boards.items()]
    plates = []
    for bay_id in rack.multi_bays() if rack else []:
        if rack.plate_kind(bay_id) != "boards":         # the honeycomb plate: nothing per bay to generate
            continue
        problems = rack.check_bay_plate(bay_id, boards)
        if problems:
            raise SystemExit(f"config/rack.yaml › population › {bay_id}: " + "; ".join(problems))
        plates.append(rackcfg.scad_value([bay_id, rack.plate_kind(bay_id), [
            [e["slot"].slot, [round(v, 3) for v in e["at"]], board_record(e["board"], boards[e["board"]], e["o"])]
            for e in rack.bay_layout(bay_id, boards)]]))
    header = [
        "// GENERATED by tools/build.py from mechanical/boards/boards.yaml — do not edit.",
        "// Boards are rotated so that their debug USB faces the drawer rear (+Y), or the right wall (+X)",
        "// for boards too long for a plug behind them (usb_side).  usb_pos runs along that edge.",
        "// [id, label, [w, l], hole_d, holes, usb_pos, usb_type, standoff, fence, height, color, verified, usb_side]",
    ]
    bay = [
        "",
        "// A converted bay's shared plate (config/rack.yaml › population › boards): its boards at their `at`, in",
        "// plate coords (front-left corner, y to the port wall), each turned USB to the port wall unless `orient: side`.",
        "// [bay, plate kind, [[slot, [x, y], board record as in BOARD_DB], ...]]",
    ]
    return ("\n".join(header) + "\nBOARD_DB = [\n  " + ",\n  ".join(rows) + "\n];\n" + "\n".join(bay)
            + "\nBAY_PLATES = [" + ("\n  " + ",\n  ".join(plates) + "\n" if plates else "") + "];\n")


def cmd_config(rack) -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "config.scad").write_text(rackcfg.scad_config(rack), encoding="utf-8")
    (GEN / "boards.scad").write_text(boards_scad(rackcfg.load_boards(), rack), encoding="utf-8")
    print("wrote", GEN / "config.scad", "and boards.scad")


# ------------------------------------------------------------------ openscad

def openscad_cmd() -> list[str]:
    exe = shutil.which("openscad") or shutil.which("openscad-nightly")
    for cand in (r"C:\Program Files\OpenSCAD\openscad.exe", r"C:\Program Files\OpenSCAD (Nightly)\openscad.exe"):
        if not exe and Path(cand).exists():
            exe = cand
    if exe and not os.environ.get("RACK_OPENSCAD_DOCKER"):
        return [exe]
    return ["docker", "run", "--rm", "-v", f"{REPO.as_posix()}:/work", "-w", "/work/mechanical",
            "openscad/openscad:latest", "openscad"]


def part_jobs(rack) -> list[tuple[str, str, dict]]:
    """(output name, scad file relative to mechanical/, -D defines)."""
    jobs = [
        ("ladder_base", "parts/ladder.scad", {"PART": "base"}),
        ("ladder_cap", "parts/ladder.scad", {"PART": "cap", "ROW": len(rack.rows)}),
        ("brace_base", "parts/brace.scad", {"ROW": -1}),
        ("tray", "parts/tray.scad", {"PART": "tray"}),
        ("floor_plate", "parts/tray.scad", {"PART": "floor_plate"}),
        ("cap_plate", "parts/tray.scad", {"PART": "cap_plate"}),
        ("drawer", "parts/drawer.scad", {}),
        ("drawer_sled", "parts/drawer.scad", {"PART": "sled"}),
        ("drawer_block", "parts/drawer.scad", {"PART": "block"}),
        ("x4_cradle", "parts/x4_cradle.scad", {}),                               # the standing DATA ×4 v2's
        ("cover_lid1", "parts/covers.scad", {"PART": "lid1"}),                   # optional: a one-board rear bay's lid
        ("cover_box4", "parts/covers.scad", {"PART": "box4"}),                   # optional: a DATA ×4 rear bay's box
        # optional, outside the rack: the standalone bays (docs/standalone.md) and the plate's desk frame
        ("standalone_solo_base", "parts/standalone.scad", {"PART": "solo_base"}),
        ("standalone_solo_lid", "parts/standalone.scad", {"PART": "solo_lid"}),
        ("standalone_quad_base", "parts/standalone.scad", {"PART": "quad_base"}),
        ("standalone_quad_shelf", "parts/standalone.scad", {"PART": "quad_shelf"}),
        ("standalone_quad_lid", "parts/standalone.scad", {"PART": "quad_lid"}),
        ("standalone_desk_frame", "parts/standalone.scad", {"PART": "desk_frame"}),
        ("chain_foot", "parts/chain_parts.scad", {"PART": "foot"}),
        ("chain_anchor", "parts/chain_parts.scad", {"PART": "anchor"}),
        ("chain_link", "parts/chain_parts.scad", {"PART": "link"}),
        ("chain_bar", "parts/chain_parts.scad", {"PART": "bar"}),
        ("plate", "parts/board_plate.scad", {}),                                # the honeycomb plate
        ("camera_pod", "parts/camera_pod.scad", {"PART": "pod"}),
        ("camera_diffuser", "parts/camera_pod.scad", {"PART": "diffuser"}),
        ("power_box_base", "parts/power_box.scad", {"PART": "base"}),
        ("power_box_lid", "parts/power_box.scad", {"PART": "lid"}),
        ("power_box_labels", "parts/power_box.scad", {"PART": "labels"}),
    ]
    for k, row in enumerate(rack.rows):      # one ladder and one brace per row (their heights differ)
        jobs.append((f"ladder_{row['id'].lower()}", "parts/ladder.scad", {"PART": "row", "ROW": k}))
        jobs.append((f"brace_{row['id'].lower()}", "parts/brace.scad", {"ROW": k}))
    for bay in rack.bays():                 # each bay's label: the body and its ID's inlay (two parts that register)
        for piece, suffix in (("body", ""), ("inlay", "_inlay")):
            jobs.append((f"bay_label_{bay.id.lower()}{suffix}", "parts/label.scad", {"ID": bay.id, "PART": piece}))
    for name, defines in plate_layout.peg_parts(rackcfg.load_boards()).items():     # its pegs
        jobs.append((name, "parts/pegs.scad", defines))
    for bay in rack.bays():                 # a bay that asks for the former plates (`plate: boards`)
        if rack.duts(bay.id) and rack.plate_kind(bay.id) == "boards":
            if rack.is_multi(bay.id):
                jobs.append((f"plate_bay_{bay.id.lower()}", "parts/board_plate.scad", {"BAY": bay.id}))
            else:
                bid = rack.duts(bay.id)[0].board
                jobs.append((f"plate_{bid}", "parts/board_plate.scad", {"BOARD": bid}))
    return [j for j in jobs if (MECH / j[1]).exists()]


STL_DIR = MECH / "stl"          # committed: printable parts, print orientation


def render(job, fmt="stl") -> tuple[str, bool, str]:
    name, scad, defines = job
    out = STL_DIR / f"{name}.{fmt}"
    out.parent.mkdir(parents=True, exist_ok=True)
    base = openscad_cmd()
    docker = base[0] == "docker"
    out_arg = f"stl/{name}.{fmt}" if docker else str(out)
    scad_arg = scad if docker else str(MECH / scad)
    cmd = base + ["--export-format", "binstl" if fmt == "stl" else fmt, "-o", out_arg]
    for k, v in defines.items():
        if isinstance(v, bool):
            v = "true" if v else "false"
            cmd += ["-D", f"{k}={v}"]
        else:
            cmd += ["-D", f'{k}="{v}"' if isinstance(v, str) else f"{k}={v}"]
    cmd.append(scad_arg)
    p = subprocess.run(cmd, capture_output=True, text=True, cwd=MECH)
    ok = p.returncode == 0 and out.exists()
    return name, ok, (p.stderr or "")[-2000:]


def cmd_stl(rack, only: list[str] | None = None) -> list[str]:
    jobs = part_jobs(rack)
    if only:
        jobs = [j for j in jobs if j[0] in only]
    failed = []
    with cf.ThreadPoolExecutor(max_workers=min(8, os.cpu_count() or 4)) as ex:
        for name, ok, err in ex.map(render, jobs):
            print(("ok   " if ok else "FAIL ") + name)
            if not ok:
                print(err)
                failed.append(name)
            elif "WARNING" in err:
                print("     " + "\n     ".join(l for l in err.splitlines() if "WARNING" in l)[:800])
    return failed


# ------------------------------------------------------------------ main

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["config", "stl", "web", "all"])
    ap.add_argument("--only", nargs="*")
    a = ap.parse_args()
    rack = rackcfg.load()
    cmd_config(rack)
    failed = []
    if a.what in ("stl", "all", "web"):
        failed = cmd_stl(rack, a.only)
    if a.what in ("web", "all"):
        import pcb_glb  # noqa: E402
        import webscene  # noqa: E402
        pcb_glb.main()          # KiCad GLBs → site/assets/pcb (skipped when no fab export exists)
        webscene.build(rack)
        import bom  # noqa: E402
        bom.main()
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
